package com.google;

public class Joueur {
    public String nom;
    public String prenom;
    public int nombre;
    public String poste;
    public String equipe;
    
    public Joueur(String nom, String prenom, int nombre, String poste, String equipe) {
        this.nom = nom;
        this.prenom = prenom;
        this.nombre = nombre;
        this.poste = poste;
        this.equipe = equipe;
    }
    
}
