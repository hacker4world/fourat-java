package com.group.training;

public class ProductRequest {
    private String name;
    private Double price;
    private int quantity;
    private int index;

    public String getName() {
        return name;
    }

    public Double getPrice() {
        return price;
    }

    public int getQuantity() {
        return quantity;
    }

    public int getIndex() {
        return index;
    }
}
